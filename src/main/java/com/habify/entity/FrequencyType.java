package com.habify.entity;

/**
 * FrequencyType
 * 
 * Defines how frequently a habit should be executed:
 * - DAILY: Scheduled every day of the week.
 * - SPECIFIC_DAYS: Scheduled only on designated days (e.g., MONDAY, WEDNESDAY, FRIDAY).
 */
public enum FrequencyType {
    DAILY,
    SPECIFIC_DAYS
}
